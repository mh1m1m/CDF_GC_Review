"""Storage layer: SQL translation for PostgreSQL (always) and live behaviour (when CDF_DATABASE_URL is set)."""
import os
import sqlite3

import pytest

from cdf_gco_crms import storage
from cdf_gco_crms.storage import _ddl, translate


def test_placeholders_and_percent_signs_are_translated_outside_literals():
    assert translate("SELECT * FROM t WHERE a=? AND b LIKE 'SYN-%' AND c='?'") == \
        "SELECT * FROM t WHERE a=%s AND b LIKE 'SYN-%%' AND c='?'"
    assert translate("INSERT INTO cp_rates VALUES (?,?,1) ON CONFLICT(session_id,window) DO UPDATE SET count=1") \
        .count('"window"') == 1


def test_ddl_types_identity_and_append_only_triggers():
    triggers = {}
    out = _ddl("""CREATE TABLE IF NOT EXISTS e (event_id INTEGER PRIMARY KEY AUTOINCREMENT, lease REAL, body BLOB);
        CREATE TABLE IF NOT EXISTS m (id INTEGER PRIMARY KEY, n INTEGER NOT NULL);
        -- comment; with a semicolon
        CREATE TRIGGER IF NOT EXISTS e_no_update BEFORE UPDATE ON e
            BEGIN SELECT RAISE(ABORT, 'AUDIT_LOG_APPEND_ONLY'); END;""", triggers)
    text = "\n".join(out)
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out[0]
    assert "DOUBLE PRECISION" in out[0] and "BYTEA" in out[0], "REAL must not become single precision"
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out[1] and "n BIGINT" in out[1]
    assert "RAISE EXCEPTION 'AUDIT_LOG_APPEND_ONLY'" in text and "CREATE OR REPLACE TRIGGER e_no_update" in text
    assert "SET search_path = pg_catalog" in text, "trigger functions pin their search_path (Supabase advisor 0011)"
    assert triggers == {"e_no_update": "e"}


def test_numbers_are_sent_untyped_and_bytes_kept():
    assert storage._param(3) == "3" and storage._param(1.5) == "1.5" and storage._param(True) == "1"
    assert storage._param(b"\x00") == b"\x00" and storage._param(None) is None


def test_sqlite_remains_the_default(tmp_path, monkeypatch):
    monkeypatch.delenv("CDF_DATABASE_URL", raising=False)
    db = storage.connect(tmp_path / "x.sqlite")
    assert isinstance(db, sqlite3.Connection) and not storage.is_postgres(db)
    db.close()


@pytest.mark.skipif(not os.getenv("CDF_DATABASE_URL"), reason="PostgreSQL behaviour needs CDF_DATABASE_URL")
def test_postgres_semantics_match_sqlite(tmp_path):
    db = storage.connect(tmp_path / "pg.sqlite")
    db.executescript("CREATE TABLE IF NOT EXISTS k (a TEXT PRIMARY KEY, n INTEGER NOT NULL);"
                     "CREATE TRIGGER IF NOT EXISTS k_no_delete BEFORE DELETE ON k BEGIN SELECT RAISE(ABORT, 'NO'); END;")
    db.execute("INSERT INTO k VALUES (?,?)", ("x", 1))
    assert db.in_transaction, "a DML statement opens a transaction, as in sqlite3"
    with pytest.raises(sqlite3.IntegrityError):
        db.execute("INSERT INTO k VALUES (?,?)", ("x", 2))
    db.execute("INSERT INTO k VALUES (?,?) ON CONFLICT DO NOTHING", ("x", 3))   # transaction still usable
    db.commit()
    row = db.execute("SELECT a, n FROM k WHERE n=?", (1,)).fetchone()
    assert row["a"] == "x" and row[1] == 1 and dict(row) == {"a": "x", "n": 1}
    with pytest.raises(sqlite3.IntegrityError, match="NO"):
        db.execute("DELETE FROM k")
    db.rollback()
    assert storage.table_exists(db, "k") and not storage.table_exists(db, "missing") and storage.integrity_ok(db)
    db.close()
